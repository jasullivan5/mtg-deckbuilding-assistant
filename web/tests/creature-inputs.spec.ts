import {expect,test} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';

test.skip(!process.env.EXPLORER_URL,'Requires the real Kotlin application.');
test('Discover separates original-creature suppliers from deaths rewards and ordinary material',async({page})=>{
  await page.goto('/');
  const completed=page.waitForResponse(r=>r.url().endsWith('/api/v1/discover')&&r.ok());
  await page.getByRole('button',{name:'Find cards',exact:true}).click();
  const run=await(await completed).json();
  const mechanic=page.getByRole('combobox',{name:'Mechanic',exact:true});
  const detail=page.getByRole('region',{name:'Result inspection'});
  const results=page.getByRole('region',{name:'Discovery results',exact:true});
  const nav=page.getByRole('navigation',{name:'Finding categories',exact:true});
  await mkdir('../generated/explorer/creature-inputs',{recursive:true});
  await mechanic.selectOption('Supplies creature inputs');
  await page.getByLabel('Card name').fill('Reassembling Skeleton');
  await expect(detail.getByRole('heading',{name:'Reassembling Skeleton',exact:true})).toBeVisible();
  const supply=detail.getByRole('region',{name:'Creature input supply'});
  await expect(supply).toContainText('{1}{B}');
  await expect(supply).toContainText('returns tapped');
  await expect(supply).toContainText('the return is not a death');
  await expect(supply).toContainText('No complete sacrifice/return cycle');
  await expect(detail.getByText('Checking the printing and complete face identities.',{exact:true})).toHaveCount(0,{timeout:45_000});
  await page.screenshot({path:'../generated/explorer/creature-inputs/discover-suppliers.png',fullPage:true});
  await detail.screenshot({path:'../generated/explorer/creature-inputs/skeleton-return.png'});
  await page.getByLabel('Card name').fill('Bloodghast');
  await expect(detail.getByRole('heading',{name:'Bloodghast',exact:true})).toBeVisible();
  await expect(supply).toContainText('land');
  await expect(supply).toContainText('optional');
  await expect(supply).toContainText('graveyard');
  await detail.screenshot({path:'../generated/explorer/creature-inputs/bloodghast-return.png'});
  await page.getByLabel('Card name').fill('Haunted Dead');
  await expect(detail.getByRole('heading',{name:'Haunted Dead',exact:true})).toBeVisible();
  await expect(supply).toContainText(/discard.*(2|two)/i);
  await page.getByLabel('Card name').fill('Grafted Butcher');
  await expect(detail.getByRole('heading',{name:'Grafted Butcher',exact:true})).toBeVisible();
  await expect(supply).toContainText('Activate only as a sorcery');
  const graft=run.cards.find((c:{card:string})=>c.card==='Grafted Butcher');
  const evidence=await(await page.request.get(`/api/v1/runs/${run.runId}/cards/${graft.index}`)).json();
  const producer=evidence.results.find((r:{branch:string;verdict:string})=>r.branch==='DIRECT_DEATH_GENERATOR'&&r.verdict==='MATCH');
  const supplier=evidence.results.find((r:{branch:string;verdict:string})=>r.branch==='INTRINSIC_CREATURE_INPUT'&&r.verdict==='MATCH');
  expect(producer.actionId).toBe(supplier.actionId);
  expect(producer.abilityPath).not.toBe(supplier.abilityPath);
  await detail.screenshot({path:'../generated/explorer/creature-inputs/grafted-overlap.png'});
  for(const name of ['Walking Corpse','Reanimate','Tymaret, the Murder King']) {
    await page.getByLabel('Card name').fill(name);
    await expect(results).toContainText('No cards in this view.');
  }
  await nav.getByRole('button',{name:/Needs interpretation/}).click();
  await mechanic.selectOption('Creature input needs investigation');
  await page.getByLabel('Card name').fill('Wolfbat');
  await expect(detail.getByRole('heading',{name:'Wolfbat',exact:true})).toBeVisible();
  await expect(supply).toContainText('needs investigation');
  await expect(supply).toContainText('finality');
  await expect(supply).toContainText('instead of a later death');
  await detail.screenshot({path:'../generated/explorer/creature-inputs/wolfbat-limits.png'});
  await nav.getByRole('button',{name:/Identified mechanics/}).click();
  await mechanic.selectOption('Supplies creature inputs');
  await page.getByLabel('Card name').fill('Reassembling Skeleton');
  await page.setViewportSize({width:390,height:844});
  await expect(supply).toContainText('{1}{B}');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await detail.screenshot({path:'../generated/explorer/creature-inputs/skeleton-mobile.png'});
  await writeFile('../generated/explorer/creature-inputs/run.json',JSON.stringify(run,null,2));
});
